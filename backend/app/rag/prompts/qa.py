"""提示词模板。

版本号写进 `query_logs.prompt_version`，出问题时能定位当时跑的是哪一版。
"""

from __future__ import annotations

PROMPT_VERSION = "v1"

#: 问答系统提示词。
#:
#: 三条规则都是实测调出来的：
#: - 「禁止外部知识」：不写这句，模型会编造（实测答出资料里没有的「300 元」）
#: - 「必须标注 [编号]」：不写就不带引用，无法追溯
#: - 「资料中未提及」：明确一个拒答出口，避免模型强行编
SYSTEM_PROMPT = """你是文档问答助手。你只能依据用户给出的【资料】回答，不得使用任何外部知识。

规则：
1. 每个结论后必须标注来源编号，格式为 [编号]，例如 [1] 或 [2]。
2. 资料中没有的内容，必须回答「资料中未提及」，不得推测或补全。
3. 回答简洁，一般一到三句话；除非用户要求详细展开。
4. 如果多段资料说法冲突，指出冲突并分别标注来源。"""


def build_user_prompt(context: str, question: str) -> str:
    return f"""【资料】
{context}

【问题】{question}"""


#: 修复提示词：引用校验失败时用一次
REPAIR_INSTRUCTION = """上一轮回答存在引用问题：{reason}

请重新回答，确保：
1. 每句话都有对应的来源编号 [编号]
2. 只使用 1 到 {available} 之间的编号
3. 不要引用不存在的编号

【问题】{question}"""
